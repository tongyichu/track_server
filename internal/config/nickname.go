func combineNicknameSeries(series ...[]string) []string {
	total := 0
	for _, group := range series {
		total += len(group)
	}
	result := make([]string, 0, total)
	for _, group := range series {
		result = append(result, group...)
	}
	return result
}

func DefaultNicknameBases() []string {
	return append([]string(nil), defaultNicknameBases...)
}
